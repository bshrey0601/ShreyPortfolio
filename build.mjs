// Builds index.html (fast, what visitors load) from source.html (readable, what you edit).
// It pre-compiles the JSX and the Tailwind CSS so the browser doesn't have to do it on every visit.
import fs from 'node:fs';
import vm from 'node:vm';
import * as esbuild from 'esbuild';
import postcss from 'postcss';
import tailwindcss from 'tailwindcss';

let html = fs.readFileSync('source.html', 'utf8');

// 1. Pull out the Tailwind config and the JSX app code.
const configTag = html.match(/<script>\s*tailwind\.config\s*=[\s\S]*?<\/script>\s*/);
const appTag = html.match(/<script type="text\/babel"[^>]*>([\s\S]*?)<\/script>/);
if (!appTag) throw new Error('Could not find the <script type="text/babel"> block in source.html');
const jsx = appTag[1];

const sandbox = { tailwind: {} };
if (configTag) vm.runInNewContext(configTag[0].replace(/<\/?script>/g, ''), sandbox);
const config = { ...(sandbox.tailwind.config || {}), content: [{ raw: jsx, extension: 'jsx' }] };

// 2. Compile the JSX (with React bundled in) into plain, minified JavaScript.
const js = (await esbuild.build({
  stdin: {
    contents: "import React from 'react'; import * as ReactDOM from 'react-dom/client';\n" + jsx,
    loader: 'jsx', resolveDir: '.',
  },
  bundle: true, minify: true, format: 'iife', write: false, jsx: 'transform',
  define: { 'process.env.NODE_ENV': '"production"' },
})).outputFiles[0].text.replace(/<\/script/g, '<\\/script');

// 3. Generate only the Tailwind CSS the site actually uses.
const tw = await postcss([tailwindcss(config)])
  .process('@tailwind base;\n@tailwind components;\n@tailwind utilities;', { from: undefined });
const css = (await esbuild.transform(tw.css, { loader: 'css', minify: true })).code;

// 4. Swap the in-browser tools for the pre-built code.
html = html
  .replace(/<script src="[^"]*(react|react-dom|babel|tailwindcss)[^"]*"[^>]*><\/script>\s*/g, '')
  .replace(configTag ? configTag[0] : '', '')
  .replace('</head>', () => `<style>${css}</style>\n</head>`)
  .replace(appTag[0], () => `<script>${js}</script>`)
  .replace(/<!DOCTYPE html>/i, (m) => `${m}\n<!-- AUTO-GENERATED from source.html. Do not edit this file; edit source.html and it rebuilds automatically. -->`);

fs.writeFileSync('index.html', html);
console.log(`Built index.html (${Math.round(html.length / 1024)} KB)`);
